// ============================================================
// BREED-SPECIFIC OVERLAY FUNCTIONS (32x32 coordinates)
// ============================================================

function applyBreedOverlays(grid, breedType, palette) {
  if (palette.stripes) {
    for (let y = 0; y < 32; y++) {
      for (let x = 0; x < 32; x++) {
        if (grid[y][x] === '1') {
          // Forehead stripes (rows 6-9, every 3rd column)
          if (y >= 6 && y <= 9 && (x === 9 || x === 13 || x === 17 || x === 21)) {
            grid[y][x] = '9';
          }
          // Body stripes (rows 18-23, every 4th column)
          if (y >= 18 && y <= 23 && (x === 7 || x === 11 || x === 15 || x === 19)) {
            grid[y][x] = '9';
          }
        }
      }
    }
  }

  if (palette.patches) {
    for (let y = 0; y < 32; y++) {
      for (let x = 0; x < 32; x++) {
        if (grid[y][x] === '1') {
          // Orange patch: left side of head + body
          if (y >= 6 && y <= 10 && x <= 9) grid[y][x] = '7';
          if (y >= 18 && y <= 22 && x <= 11) grid[y][x] = '7';
          // Dark patch: right side of body
          if (y >= 18 && y <= 22 && x >= 18 && x <= 23) grid[y][x] = '8';
          if (y >= 8 && y <= 10 && x >= 20) grid[y][x] = '8';
        }
      }
    }
  }

  if (palette.tuxedo) {
    for (let y = 0; y < 32; y++) {
      for (let x = 0; x < 32; x++) {
        if (grid[y][x] === '1' || grid[y][x] === '2') {
          // White chin/lower face
          if (y >= 14 && y <= 17 && x >= 8 && x <= 19) grid[y][x] = '7';
          // White chest/belly
          if (y >= 18 && y <= 23 && x >= 8 && x <= 19) grid[y][x] = '7';
          // White paws
          if (y >= 24 && y <= 27) grid[y][x] = '7';
        }
      }
    }
  }

  if (palette.points) {
    for (let y = 0; y < 32; y++) {
      for (let x = 0; x < 32; x++) {
        const ch = grid[y][x];
        if (ch === '1' || ch === '3' || ch === '6') {
          // Dark ears
          if (y >= 2 && y <= 5) grid[y][x] = '7';
          // Dark face mask around nose
          if (y >= 14 && y <= 17 && x >= 10 && x <= 19) grid[y][x] = '7';
          // Dark paws
          if (y >= 24 && y <= 27) grid[y][x] = '7';
          // Dark tail
          if (x >= 26 && y >= 20) grid[y][x] = '7';
        }
      }
    }
  }
}

// ============================================================
// SVG GENERATION (32x32 viewBox)
// ============================================================

function generateCatSVG(frameKey, breedType) {
  const template = FRAME_TEMPLATES[frameKey];
  const palette = BREED_PALETTES[breedType];
  if (!template || !palette) return '';

  const grid = template.map(row => row.split(''));
  applyBreedOverlays(grid, breedType, palette);

  let rects = '';
  for (let y = 0; y < 32; y++) {
    for (let x = 0; x < 32; x++) {
      const ch = grid[y][x];
      if (ch === '.') continue;
      const color = palette[ch];
      if (!color) continue;
      rects += '<rect x="' + x + '" y="' + y + '" width="1" height="1" fill="' + color + '"/>';
    }
  }

  const svg = '<svg viewBox="0 0 32 32" xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges">' + rects + '</svg>';
  return 'data:image/svg+xml,' + encodeURIComponent(svg);
}

// ============================================================
// SPRITE CACHE
// ============================================================

const SPRITE_CACHE = {};

function preRenderAllSprites() {
  const breeds = Object.keys(BREED_PALETTES);
  const frames = Object.keys(FRAME_TEMPLATES);
  for (const breed of breeds) {
    for (const frame of frames) {
      const key = breed + ':' + frame;
      SPRITE_CACHE[key] = generateCatSVG(frame, breed);
    }
  }
}

function getCachedSprite(breed, frame) {
  const key = breed + ':' + frame;
  if (SPRITE_CACHE[key]) return SPRITE_CACHE[key];
  const uri = generateCatSVG(frame, breed);
  SPRITE_CACHE[key] = uri;
  return uri;
}

