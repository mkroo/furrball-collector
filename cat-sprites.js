// ============================================================
// BREED-SPECIFIC OVERLAY FUNCTIONS (32x32 coordinates)
// ============================================================

function applyBreedOverlays(grid, breedType, palette) {
  if (palette.stripes) {
    // Tabby stripes: forehead M-mark + 3-4 horizontal body stripes
    for (let y = 0; y < 32; y++) {
      for (let x = 0; x < 32; x++) {
        if (grid[y][x] === '1' || grid[y][x] === '3') {
          // Forehead M-mark
          if (y >= 8 && y <= 9 && (x === 10 || x === 12 || x === 14 || x === 16)) {
            grid[y][x] = '9';
          }
          // Body horizontal stripes
          if (y === 17 && x >= 8 && x <= 22 && x % 3 === 0) grid[y][x] = '9';
          if (y === 19 && x >= 7 && x <= 23 && x % 3 === 1) grid[y][x] = '9';
          if (y === 21 && x >= 7 && x <= 22 && x % 3 === 2) grid[y][x] = '9';
        }
      }
    }
  }

  if (palette.patches) {
    // Calico: asymmetric orange + dark patches
    for (let y = 0; y < 32; y++) {
      for (let x = 0; x < 32; x++) {
        if (grid[y][x] === '1' || grid[y][x] === '3') {
          // Orange patch: left upper body
          if (y >= 8 && y <= 13 && x >= 8 && x <= 13) grid[y][x] = '7';
          if (y >= 16 && y <= 19 && x >= 7 && x <= 12) grid[y][x] = '7';
          // Dark patch: right lower body
          if (y >= 19 && y <= 22 && x >= 17 && x <= 22) grid[y][x] = '8';
          if (y >= 9 && y <= 11 && x >= 16 && x <= 19) grid[y][x] = '8';
        }
      }
    }
  }

  if (palette.tuxedo) {
    // White chest, belly, chin, paws
    for (let y = 0; y < 32; y++) {
      for (let x = 0; x < 32; x++) {
        if (grid[y][x] === '1' || grid[y][x] === '2') {
          // White chin
          if (y >= 12 && y <= 13 && x >= 11 && x <= 15) grid[y][x] = '7';
          // White chest/belly
          if (y >= 18 && y <= 22 && x >= 9 && x <= 17) grid[y][x] = '7';
          // White paws
          if (y >= 25 && y <= 28) grid[y][x] = '7';
        }
      }
    }
  }

  if (palette.points) {
    // Siamese: dark ears, face mask, paws, tail tip
    for (let y = 0; y < 32; y++) {
      for (let x = 0; x < 32; x++) {
        const ch = grid[y][x];
        if (ch === '1' || ch === '3' || ch === '6') {
          // Dark ears
          if (y >= 5 && y <= 7 && (x <= 12 || x >= 17)) {
            if (ch === '6' || ch === '3') grid[y][x] = '7';
          }
          // Dark face mask around nose
          if (y >= 11 && y <= 13 && x >= 12 && x <= 16) grid[y][x] = '7';
          // Dark paws
          if (y >= 25 && y <= 28) grid[y][x] = '7';
          // Dark tail (rightmost outline-adjacent body pixels at tail)
          if (y >= 23 && x >= 24) grid[y][x] = '7';
        }
      }
    }
  }
}

// ============================================================
// SVG GENERATION (32x32 viewBox)
// ============================================================

function generateCatSVG(frameKey, breedType) {
  const template = FRAME_TEMPLATES[frameKey];
  const palette = BREED_PALETTES[breedType];
  if (!template || !palette) return '';

  const grid = template.map(row => row.split(''));
  applyBreedOverlays(grid, breedType, palette);

  let rects = '';
  for (let y = 0; y < 32; y++) {
    for (let x = 0; x < 32; x++) {
      const ch = grid[y][x];
      if (ch === '.') continue;
      const color = palette[ch];
      if (!color) continue;
      rects += `<rect x="${x}" y="${y}" width="1" height="1" fill="${color}"/>`;
    }
  }

  const svg = `<svg viewBox="0 0 32 32" xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges">${rects}</svg>`;
  return 'data:image/svg+xml,' + encodeURIComponent(svg);
}

// ============================================================
// SPRITE CACHE
// ============================================================

const SPRITE_CACHE = {};

function preRenderAllSprites() {
  const breeds = Object.keys(BREED_PALETTES);
  const frames = Object.keys(FRAME_TEMPLATES);
  for (const breed of breeds) {
    for (const frame of frames) {
      const key = breed + ':' + frame;
      SPRITE_CACHE[key] = generateCatSVG(frame, breed);
    }
  }
}

function getCachedSprite(breed, frame) {
  const key = breed + ':' + frame;
  if (SPRITE_CACHE[key]) return SPRITE_CACHE[key];
  const uri = generateCatSVG(frame, breed);
  SPRITE_CACHE[key] = uri;
  return uri;
}

